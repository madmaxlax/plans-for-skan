#!/usr/bin/env node
// Pulls the next week of Skaneateles Community Center fitness classes from
// clubautomation.com and writes a clean JSON to data/scc-classes.json.
//
// Usage:
//   SCC_COOKIE='PHPSESSID=...; isLoggedIn=1; cf_clearance=...; __cf_bm=...' \
//   node scripts/fetch-scc-classes.mjs
//
// Cookies live in your browser session — grab them from a logged-in session
// at https://skancc.clubautomation.com and paste into SCC_COOKIE. They expire,
// so re-run as needed.

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(__dirname, "..", "data", "scc-classes.json");

const cookie = process.env.SCC_COOKIE;
if (!cookie) {
  console.error("ERR: set SCC_COOKIE env var (paste browser cookies from a logged-in skancc.clubautomation.com tab).");
  process.exit(1);
}

const res = await fetch("https://skancc.clubautomation.com/calendar/classes-by-date", {
  method: "POST",
  headers: {
    accept: "*/*",
    "content-type": "application/x-www-form-urlencoded; charset=UTF-8",
    "x-requested-with": "XMLHttpRequest",
    referer: "https://skancc.clubautomation.com/calendar/classes?tab=by-date",
    cookie,
  },
  body: "tab=by-date&isFrame=0",
});
if (!res.ok) {
  console.error(`ERR: HTTP ${res.status}`);
  process.exit(1);
}
const html = await res.text();

// The response is a flat HTML block. Dates appear as headers like
// "Monday, June 1, 2026" and each class is a <div class="block event ...">.
// We walk the events in document order and tag them with the most recent date.

const MONTHS = { January:1, February:2, March:3, April:4, May:5, June:6, July:7, August:8, September:9, October:10, November:11, December:12 };
function toISO(monthName, day, year) {
  const m = String(MONTHS[monthName]).padStart(2, "0");
  const d = String(day).padStart(2, "0");
  return `${year}-${m}-${d}`;
}

// Find all date headers and event blocks with their character offsets, then
// pair each event to the nearest preceding date header.
// Headers look like: "Monday | June 01, 2026"
const dateRe = /(Sunday|Monday|Tuesday|Wednesday|Thursday|Friday|Saturday)\s*\|\s*(January|February|March|April|May|June|July|August|September|October|November|December)\s+(\d{1,2}),\s+(\d{4})/g;
const dateMarks = [];
for (const m of html.matchAll(dateRe)) {
  dateMarks.push({ pos: m.index, iso: toISO(m[2], parseInt(m[3], 10), parseInt(m[4], 10)) });
}

// Each class is a <div class="block ... row_N"> — sometimes "block event row_N",
// sometimes just "block row_N". We slice from one "block ... row_" opener to the next.
const blockStarts = [];
for (const m of html.matchAll(/<div class="block(?: event)? row_\d+"\s*>/g)) {
  blockStarts.push(m.index);
}

const classes = [];
let unknownDate = 0;
for (let i = 0; i < blockStarts.length; i++) {
  const pos = blockStarts[i];
  const endPos = i + 1 < blockStarts.length ? blockStarts[i + 1] : html.length;
  const block = html.slice(pos, endPos);

  // Walk dateMarks to find the most recent date <= pos.
  let iso = null;
  for (const dm of dateMarks) {
    if (dm.pos <= pos) iso = dm.iso; else break;
  }

  const timeMatch = block.match(/<span class="time">\s*([^<]+?)\s*<\/span>/);
  const titleMatch = block.match(/class="row_link"[^>]*>\s*([^<]+?)\s*<\/a>/);
  const facilityMatch = block.match(/<span class="row_label">Facility:<\/span>\s*([^<\n]+?)\s*</);
  const instructorMatch = block.match(/<strong class="row_label">Instructor:<\/strong>\s*([^<\n]+?)\s*</);
  const statusMatch = block.match(/<button class="btn register_button register-button-(\w+)"/);

  if (!timeMatch || !titleMatch) continue;
  if (!iso) { unknownDate++; continue; }

  // "07:15am - 08:00am" → split into start/end
  const time = timeMatch[1].trim();
  const [start, end] = time.split(/\s*-\s*/).map((s) => s.trim());

  classes.push({
    date: iso,
    timeStart: start,
    timeEnd: end,
    title: titleMatch[1].trim(),
    facility: facilityMatch?.[1].trim() || "",
    instructor: instructorMatch?.[1].trim() || "",
    status: statusMatch?.[1] || "unknown",
  });
}

classes.sort((a, b) => (a.date + a.timeStart).localeCompare(b.date + b.timeStart));

const dates = [...new Set(classes.map((c) => c.date))].sort();
const out = {
  _doc: "Auto-generated by scripts/fetch-scc-classes.mjs from skancc.clubautomation.com. Do not hand-edit — re-run the script with a fresh SCC_COOKIE.",
  fetchedAt: new Date().toISOString(),
  dateRange: dates.length ? { start: dates[0], end: dates[dates.length - 1] } : null,
  count: classes.length,
  classes,
};

writeFileSync(OUT, JSON.stringify(out, null, 2) + "\n");
console.log(`Wrote ${classes.length} classes (${dates.length} days) → ${OUT}`);
if (unknownDate) console.warn(`Note: ${unknownDate} events skipped — no preceding date header.`);
